#!/usr/bin/env node
// Style guard (run by `npm run lint`, hence by `make lint` / `make check`).
// Styling in Arenile mobile = React Native Reusables components + NativeWind
// (Tailwind) utilities on theme tokens only (ADR 0004, src/components/ui/README.md),
// mirroring the core css-guard (core ADR 0009). This script fails on:
//   1. stylesheets other than the theme file src/global.css;
//   2. CSS-in-JS libraries and stylesheet imports other than the theme file;
//   3. inline `style={...}`, `StyleSheet` (create, absoluteFill...) and `style:` objects;
//   4. raw colours in code: hex literals, rgb()/hsl()/oklch()... colour functions;
//   5. Tailwind arbitrary values that bypass the theme: raw colours (`bg-[#…]`),
//      custom typography (`text-[10px]`), pixel lengths (`w-[2px]`), arbitrary
//      properties (`[elevation:2]`) and custom properties (`[--x:…]`);
//   6. the default Tailwind palette (`bg-red-500`, `text-white`, `border-slate-200`):
//      use the semantic tokens (bg-destructive, text-primary-foreground, border-border).
// The only exemptions are listed below, each with its reason. Do not add to them
// without updating ADR 0004 (or the ADR that adds them, e.g. 0008).
const { readFileSync, readdirSync, statSync } = require('node:fs');
const { join, relative, sep } = require('node:path');

const ROOT = join(__dirname, '..');
const SCAN = ['src'];
const SKIP_DIRS = new Set(['node_modules', 'generated', '__snapshots__']);

/** The only stylesheet: Reusables theme variables for NativeWind. */
const ALLOWED_STYLESHEETS = new Set(['src/global.css']);

/** Reusables components as generated by their CLI (vendored, kept verbatim where possible). */
const VENDORED_RE = /^src\/components\/ui\/[^/]+\.tsx$/;

/** Raw colour exemptions, with their reason. */
const RAW_COLOUR_ALLOW = new Set([
  // React Navigation needs concrete colours (it cannot read CSS variables);
  // src/lib/theme.test.ts keeps them equal to src/global.css.
  'src/lib/theme.ts',
  // react-native-svg props of the day map (hundreds of shapes): concrete colours,
  // no per-element class resolution (ADR 0008); src/features/day-map/palette.test.ts
  // keeps them equal to src/global.css.
  'src/features/day-map/palette.ts',
]);

/** Inline style / StyleSheet exemptions, with their reason. */
const STYLE_ALLOW = new Set([]);

const CSS_IN_JS = [
  'styled-components',
  '@emotion/',
  'styled-jsx',
  '@stitches/',
  '@vanilla-extract/',
  '@linaria/',
  'goober',
  'jss',
  'aphrodite',
  'twin.macro',
  'react-native-extended-stylesheet',
  'restyle',
  '@shopify/restyle',
  'tamagui',
  '@tamagui/',
];

const STYLESHEET_RE = /\.(css|scss|sass|less|styl|pcss)$/i;
const SOURCE_RE = /\.(ts|tsx|js|jsx|mjs|cjs)$/;
const TEST_RE = /\.test\.(ts|tsx|js)$/;
const IMPORT_RE = /(?:import\s[^'"]*?from\s*|import\s*\(?\s*|require\(\s*)['"]([^'"]+)['"]/g;
// expo-status-bar's `<StatusBar style="light">` is a colour mode, not a style object.
// Any style prop (style, contentContainerStyle, imageStyle...), StyleSheet, style objects.
const STYLE_RE =
  /(?<!<StatusBar\s[^>]*)\b\w*[sS]tyle=\{|\bStyleSheet\b|\b\w*[sS]tyle:\s*\{|\b\w*[sS]tyle:\s*\[/g;
// Colour props with a literal value (color="red", placeholderTextColor={'white'}).
const COLOUR_PROP_RE = /\b\w*[cC]olor=\s*(?:["']|\{\s*["'`])/g;
const RAW_COLOUR_RE =
  /['"`]#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})['"`]|\b(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb)\(/g;
const PALETTE =
  'black|white|slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose';
const PALETTE_RE = new RegExp(
  `(?<![\\w-])(?:[a-z-]+:)*(?:bg|text|border(?:-[trblxy])?|ring|ring-offset|shadow|fill|stroke|outline|decoration|divide|placeholder|caret|accent|from|via|to)-(?:${PALETTE})(?:-\\d{2,3})?(?:\\/\\d+)?(?![\\w-])`,
  'g',
);

/** Arbitrary values that bypass the theme (message, regex). */
const ARBITRARY = [
  [
    'raw colour (use a theme token: bg-primary, text-muted-foreground…)',
    /-\[(#|rgba?\(|hsla?\(|oklch\(|oklab\(|lab\(|lch\(|color\()/g,
  ],
  [
    'custom typography (use text-xs…text-2xl, tracking-wide…)',
    /\b(?:text|leading|tracking|font)-\[[^\]]*\]/g,
  ],
  ['pixel length (use the spacing scale or a layout unit: rem, %)', /-\[\d+(?:\.\d+)?px\]/g],
  [
    'arbitrary CSS property (use a utility or a component variant)',
    /(?<![&\w-])\[[a-z][a-z-]*:[^\]]*\]/g,
  ],
  [
    'arbitrary custom property (theme variables live in src/global.css)',
    /(?<![&\w-])\[--[a-z][a-z0-9-]*:[^\]]*\]/g,
  ],
];

const lineOf = (text, index) => text.slice(0, index).split('\n').length;

/**
 * Checks one file (pure, exported for tests). `path` is repository-relative
 * with forward slashes. Returns "path:line: message" strings.
 */
function checkFile(path, text) {
  const errors = [];
  const fail = (index, msg) => errors.push(`${path}:${lineOf(text, index)}: ${msg}`);

  if (STYLESHEET_RE.test(path)) {
    if (!ALLOWED_STYLESHEETS.has(path)) {
      errors.push(
        `${path}: stylesheet not allowed (use Reusables variants + NativeWind utilities)`,
      );
    }
    return errors;
  }
  if (!SOURCE_RE.test(path)) return errors;

  for (const m of text.matchAll(IMPORT_RE)) {
    const spec = m[1];
    if (CSS_IN_JS.some((lib) => spec === lib || spec.startsWith(lib))) {
      fail(m.index, `CSS-in-JS library "${spec}" not allowed`);
    }
    if (STYLESHEET_RE.test(spec) && !/(^|\/)global\.css$/.test(spec)) {
      fail(m.index, `stylesheet import "${spec}" not allowed (only src/global.css)`);
    }
  }

  // Tests may contain the fragments the guard must reject.
  if (TEST_RE.test(path)) return errors;

  if (!STYLE_ALLOW.has(path)) {
    for (const m of text.matchAll(STYLE_RE)) {
      fail(m.index, `"${m[0].trim()}" not allowed (use className with theme utilities)`);
    }
    for (const m of text.matchAll(COLOUR_PROP_RE)) {
      fail(
        m.index,
        `colour prop "${m[0].trim()}" with a literal value (use className with a theme token)`,
      );
    }
  }
  if (!RAW_COLOUR_ALLOW.has(path)) {
    for (const m of text.matchAll(RAW_COLOUR_RE)) {
      fail(m.index, `raw colour ${m[0]} not allowed (use a theme token)`);
    }
  }
  // Vendored Reusables components keep the palette shades and arbitrary values
  // their generator emits (shadow-black/5, bg-black/50, h-[1px], ring-[3px]).
  if (VENDORED_RE.test(path)) return errors;
  for (const m of text.matchAll(PALETTE_RE)) {
    fail(m.index, `default palette colour "${m[0]}" not allowed (use a semantic theme token)`);
  }
  for (const [msg, re] of ARBITRARY) {
    for (const m of text.matchAll(re)) {
      fail(m.index, `Tailwind arbitrary value "${m[0]}": ${msg}`);
    }
  }
  return errors;
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name) || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function run() {
  const errors = [];
  for (const top of SCAN) {
    for (const file of walk(join(ROOT, top))) {
      const path = relative(ROOT, file).split(sep).join('/');
      errors.push(...checkFile(path, readFileSync(file, 'utf8')));
    }
  }
  if (errors.length > 0) {
    console.error(`style-guard: ${errors.length} problem(s)\n${errors.join('\n')}`);
    console.error('See ADR 0004 and src/components/ui/README.md.');
    process.exit(1);
  }
  console.log('style-guard: ok');
}

module.exports = { checkFile };

if (require.main === module) run();
